    private void llenarComboBox() {
        jComboBox1.removeAllItems();
        int i=0;
        ArrayList<String> nombres = gPersona.getNombres();
        for (String nombre : nombres) {
            jComboBox1.addItem(i + "." + nombre);
            i++;
        }
    }

