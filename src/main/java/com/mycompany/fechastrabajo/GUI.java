    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        Integer indexPersona = jComboBox1.getSelectedIndex();
        Persona persona = gPersona.seleccionarPersona(indexPersona);
        boolean estado = persona.getEstado();
        LocalDate fechaNacimiento = persona.getFechaNacimiento();

        String s = (String) evt.getActionCommand();
        if (s.equals("Edad")) {
            if (estado) {
                String edadAños = "" + gestionFechas.yearsBetween(gestionFechas.fechaHoy, fechaNacimiento) + "";
                jLabel3.setText(persona.getNombre() + " tiene " + edadAños + " años.");
            }
        }
    }                                        

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        Integer indexPersona = jComboBox1.getSelectedIndex();
        Persona persona = gPersona.seleccionarPersona(indexPersona);
        LocalDate fechaMatrimonio = persona.getFechaMatrimonio();

        String s = (String) evt.getActionCommand();
        if (s.equals("Años casado")) {
            if (fechaMatrimonio != null) {
                String añosCasado = "" + gestionFechas.yearsBetween(gestionFechas.fechaHoy, fechaMatrimonio) + "";
                jLabel3.setText(persona.getNombre() + " lleva " + añosCasado + " años casado.");
            } else {
                jLabel3.setText(persona.getNombre() + " aún no se ha casado.");
            }
        }
    }                                        

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        Integer indexPersona = jComboBox1.getSelectedIndex();
        Persona persona = gPersona.seleccionarPersona(indexPersona);
        LocalDate fechaLoteria = persona.getFechaLoteria();
        LocalDate fechaMuerte = persona.getFechaMuerte();

        String s = (String) evt.getActionCommand();
        if (s.equals("Loteria-Ahora")) {
            if (fechaLoteria != null) {
                if (persona.getEstado()) {
                    String segundosDesdeLoteria = "" + gestionFechas.secondsBetween(gestionFechas.fechaHoy, fechaLoteria) + "";
                    jLabel3.setText(persona.getNombre() + " lleva " + segundosDesdeLoteria + " segundos vivo desde que se ganó la lotería.");
                } else {
                    String segundosDesdeLoteria = "" + gestionFechas.secondsBetween(gestionFechas.fechaHoy, fechaMuerte) + "";
                    jLabel3.setText(persona.getNombre() + " vivió  " + segundosDesdeLoteria + " segundos después de que se ganó la lotería.");
                }
            } else {
                jLabel3.setText(persona.getNombre() + " No se ha ganado la lotería");
            }
    }                                        
    }
    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        Integer indexPersona = jComboBox1.getSelectedIndex();
        Persona persona = gPersona.seleccionarPersona(indexPersona);
        LocalDate fechaGrados = persona.getFechaGrado();
        LocalDate fechaMatrimonio = persona.getFechaMatrimonio();

        String s = (String) evt.getActionCommand();
        if (s.equals("Grados-Matrimonio")) {
            String diasGraduadoCasado = "" + gestionFechas.daysBetween(fechaGrados, fechaMatrimonio) + "";
            jLabel3.setText(persona.getNombre() + " lleva " + diasGraduadoCasado + " dias casado desde que se graduó.");
        }
    }                                        

